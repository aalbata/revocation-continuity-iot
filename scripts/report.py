"""Write the results tables in results/tables.md from results/manifest.json.

The same tables appear in the README. Every value is formatted here from the
manifest; nothing is typed by hand.

Usage: python scripts/report.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ORDER = ["online", "cached", "shortlived", "coordinated", "profile", "no_inherit", "no_persist", "no_session",
         "timer_reset"]
OUTAGES = [0, 5, 30, 120]


def interval(entry: dict, scale: float = 1.0, digits: int = 1) -> str:
    if entry is None:
        return "n/a"
    return (f"{entry['mean'] * scale:.{digits}f} "
            f"[{entry['ci_low'] * scale:.{digits}f}, {entry['ci_high'] * scale:.{digits}f}]")


def main() -> None:
    with open(os.path.join(ROOT, "results", "manifest.json"), encoding="utf-8") as handle:
        manifest = json.load(handle)
    primary = manifest["live"]["primary"]
    labels = {key: value["label"] for key, value in manifest["policies"].items()}
    lines = ["# Results tables", "",
             "Generated by `scripts/report.py` from `results/manifest.json`. Values are means over independent runs",
             "with 95 percent bootstrap intervals over runs in brackets.", ""]
    lines += ["## Time from revocation commit to the last newly executed unauthorized command (s)", "",
              "| Policy | " + " | ".join(f"Outage {o} s" for o in OUTAGES) + " |", "|---|" + "---|" * len(OUTAGES)]
    for policy in ORDER:
        cells = []
        for outage in OUTAGES:
            entry = primary.get(f"{policy}-o{outage}")
            if not entry:
                cells.append("n/a")
                continue
            mark = f" (censored in {entry['censored']} of {entry['runs'] - entry['failed']})" if entry["censored"] else ""
            cells.append(interval(entry["exposure_max"]) + mark)
        lines.append(f"| {labels[policy]} | " + " | ".join(cells) + " |")
    lines += ["", "## Benign commands completed within one second (percent)", "",
              "| Policy | " + " | ".join(f"Outage {o} s" for o in OUTAGES) + " |", "|---|" + "---|" * len(OUTAGES)]
    for policy in ORDER:
        cells = [interval(primary[f"{policy}-o{o}"]["completion"], 100.0) if f"{policy}-o{o}" in primary else "n/a"
                 for o in OUTAGES]
        lines.append(f"| {labels[policy]} | " + " | ".join(cells) + " |")
    lines += ["", "## Cost at an outage of 30 s", "",
              "| Policy | Unauthorized share (percent) | Command latency p95 (ms) | Backhaul traffic (kB per run) | "
              "Token renewals per run | Runs | Failed |", "|---|---|---|---|---|---|---|"]
    for policy in ORDER:
        entry = primary.get(f"{policy}-o30")
        if not entry:
            continue
        lines.append(f"| {labels[policy]} | {interval(entry['unauthorized_fraction'], 100.0)} | "
                     f"{interval(entry['latency_ms_p95'], 1.0, 2)} | {interval(entry['backhaul_kb'], 1.0, 0)} | "
                     f"{interval(entry['renewals'], 1.0, 1)} | {entry['runs']} | {entry['failed']} |")
    interop = manifest.get("interop")
    if interop:
        lines += ["", "## Interoperability fixtures", "",
                  f"{interop['agree']} of {interop['fixtures']} fixtures gave the same verdict in both stacks.", ""]
        for row in interop["rows"]:
            if not row["agree"]:
                lines.append(f"- `{row['name']}` ({row['note']}): Python {row['python']['verdict']}, "
                             f"Node.js {row['node']['verdict']}, expected {row['expect']}")
    check = manifest.get("sim_validation")
    if check:
        lines += ["", "## Simulation against live measurement", "",
                  f"Across {check['conditions_without_censoring']} uncensored conditions the mean absolute difference "
                  f"in exposure is {check['exposure_mean_abs_error_s']:.2f} s (largest {check['exposure_max_abs_error_s']:.2f} s). "
                  f"Across {check['conditions']} conditions the mean absolute difference in completion is "
                  f"{100 * check['completion_mean_abs_error']:.2f} percentage points "
                  f"(largest {100 * check['completion_max_abs_error']:.2f})."]
    with open(os.path.join(ROOT, "results", "tables.md"), "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")
    readme = os.path.join(ROOT, "README.md")
    with open(readme, encoding="utf-8") as handle:
        text = handle.read()
    start, end = "<!-- results:start -->", "<!-- results:end -->"
    head, rest = text.split(start)
    tail = rest.split(end)[1]
    body = "\n".join(line.replace("## ", "### ") for line in lines[2:])
    with open(readme, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(head + start + "\n" + body + "\n" + end + tail)
    print("\n".join(lines[5:16]))


if __name__ == "__main__":
    main()
