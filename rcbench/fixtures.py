"""Interoperability fixtures processed by both verification stacks.

Every fixture is built deterministically from fixed seeds and a fixed clock, so
the files in fixtures/ can be regenerated byte for byte. Each fixture names the
operation to run (credential, presentation, or status), the inputs, and the
expected outcome under the pinned profile. run_stack applies one stack to one
fixture and returns a normalized verdict; compare classifies any disagreement.
"""
import copy
import hashlib
import json

from . import di, vc
from .statuslist import EXT_CONTEXT_DOCUMENT, V2_CONTEXT, Bitstring, list_credential, status_entry

NOW = 1790000000.0
ISSUER = "did:web:issuer-a.rcbench.test"
OTHER = "did:web:issuer-b.rcbench.test"
LIST = "https://issuer-a.rcbench.test/status/revocation"
SUSPENSION = "https://issuer-a.rcbench.test/status/suspension"


def _key(did: str, name: str) -> di.KeyPair:
    return di.KeyPair(did, name, hashlib.sha256(f"fixture:{did}:{name}".encode()).digest())


def _document(did: str, keys: list) -> dict:
    ids = [k.id for k in keys]
    return {"@context": [di.DID_CONTEXT, di.MULTIKEY_CONTEXT], "id": did,
            "verificationMethod": [k.method() for k in keys], "assertionMethod": ids, "authentication": ids}


def build(node: vc.NodeVerifier | None = None) -> list:
    """Return the fixture list. A Node verifier is needed only for the fixtures issued by that stack."""
    key1, key2 = _key(ISSUER, "key-1"), _key(ISSUER, "key-2")
    other = _key(OTHER, "key-1")
    holder = di.did_key_from_seed(hashlib.sha256(b"fixture:holder").digest())
    stranger = di.did_key_from_seed(hashlib.sha256(b"fixture:stranger").digest())
    docs = {ISSUER: _document(ISSUER, [key1]), OTHER: _document(OTHER, [other])}
    rotated = {ISSUER: _document(ISSUER, [key1, key2]), OTHER: docs[OTHER]}
    removed = {ISSUER: _document(ISSUER, [key2]), OTHER: docs[OTHER]}

    def credential(index=7, valid_from=NOW - 60, valid_until=NOW + 3600, purpose="revocation", listed=LIST):
        return vc.device_credential("urn:uuid:5f0c1a2e-6d1b-4c56-9a51-0d7c8e3b2a10", ISSUER, holder.controller,
                                    "d001", "contractor", ["command"], valid_from, valid_until,
                                    [status_entry(listed, purpose, index)])

    def signed(document, key=key1, purpose="assertionMethod", **kw):
        return di.add_proof(document, key, purpose, NOW - 30, **kw)

    def status_list(flags=(), issuer=ISSUER, key=key1, purpose="revocation", listed=LIST, length=131072,
                    valid_until=NOW + 20 * 365 * 86400.0):
        bits = Bitstring(length)
        for index in flags:
            bits.set(index, True)
        coverage = {"authority": issuer, "epoch": "fixture", "sequence": 1 + len(flags), "covered_through": NOW - 5}
        return signed(list_credential(listed, issuer, purpose, bits, NOW - 5, valid_until, 5000, coverage), key)

    good = signed(credential())
    fixtures = []

    def add(name, operation, expect, note, **inputs):
        fixtures.append({"name": name, "operation": operation, "expect": expect, "note": note,
                         "documents": inputs.pop("documents", docs), **inputs})

    add("credential-valid", "credential", "accept", "issued by the Python stack", credential=good)
    if node is not None:
        add("credential-valid-node-issued", "credential", "accept", "issued by the Node.js stack",
            credential=node.issue(credential(), key1, "assertionMethod", NOW - 30))
    tampered = copy.deepcopy(good)
    tampered["credentialSubject"]["deviceId"] = "d999"
    add("credential-tampered-claim", "credential", "reject", "a claim was changed after signing", credential=tampered)
    broken = copy.deepcopy(good)
    value = broken["proof"]["proofValue"]
    broken["proof"]["proofValue"] = value[:-2] + ("11" if not value.endswith("11") else "22")
    add("credential-tampered-proof", "credential", "reject", "the proof value was changed", credential=broken)
    add("credential-expired", "credential", "reject", "validUntil is in the past",
        credential=signed(credential(valid_from=NOW - 7200, valid_until=NOW - 3600)))
    add("credential-not-yet-valid", "credential", "reject", "validFrom is in the future",
        credential=signed(credential(valid_from=NOW + 3600, valid_until=NOW + 7200)))
    add("credential-unknown-key", "credential", "reject", "signed with a key that is absent from the DID document",
        credential=signed(credential(), key2))
    add("credential-foreign-signer", "credential", "reject", "signed by another issuer's key",
        credential=signed(credential(), other))
    add("credential-after-rotation", "credential", "accept", "earlier key still listed after rotation",
        credential=good, documents=rotated)
    add("credential-key-removed", "credential", "reject", "signing key removed from the DID document",
        credential=good, documents=removed)
    inline = credential()
    inline["@context"] = [V2_CONTEXT, EXT_CONTEXT_DOCUMENT["@context"]]
    add("credential-inline-context", "credential", "accept", "extension terms given as an inline context object",
        credential=signed(inline))

    def present(key=holder, challenge="c-123", domain="building", held=good):
        unsigned = vc.presentation(key.controller, [held])
        return di.add_proof(unsigned, key, "authentication", NOW - 1, challenge, domain)

    add("presentation-valid", "presentation", "accept", "holder proof with challenge and domain",
        presentation=present(), challenge="c-123", domain="building")
    add("presentation-wrong-challenge", "presentation", "reject", "challenge differs from the one issued",
        presentation=present(), challenge="c-999", domain="building")
    add("presentation-wrong-domain", "presentation", "reject", "proof was made for another domain",
        presentation=present(), challenge="c-123", domain="provider")
    add("presentation-bad-credential", "presentation", "reject", "embedded credential was tampered",
        presentation=present(held=tampered), challenge="c-123", domain="building")
    replayed = present()
    replayed["holder"] = stranger.controller
    add("presentation-holder-changed", "presentation", "reject", "holder field changed after signing",
        presentation=replayed, challenge="c-123", domain="building")

    add("status-clear", "status", "clear", "bit not set", credential=good, lists=[status_list()])
    add("status-set", "status", "set", "bit set", credential=good, lists=[status_list([7])])
    add("status-other-entry-set", "status", "clear", "a different entry is set", credential=good,
        lists=[status_list([8])])
    add("status-reused-index", "status", "set", "a new credential that reuses a revoked index",
        credential=signed(dict(credential(), id="urn:uuid:0b9d7c1e-2f4a-4b7e-8a3d-6c5e4f3a2b1c")),
        lists=[status_list([7])])
    add("status-purpose-mismatch", "status", "error", "list purpose differs from the entry purpose",
        credential=good, lists=[status_list(purpose="suspension")])
    add("status-foreign-issuer", "status", "error", "list signed by another issuer",
        credential=good, lists=[status_list(issuer=OTHER, key=other)])
    add("status-list-tampered", "status", "error", "encoded list changed after signing",
        credential=good, lists=[dict(status_list(), credentialSubject=dict(
            status_list()["credentialSubject"], encodedList=status_list([7])["credentialSubject"]["encodedList"]))])
    add("status-list-missing", "status", "error", "the list cannot be retrieved", credential=good, lists=[])
    add("status-list-short", "status", "error", "list has fewer than 131,072 entries",
        credential=good, lists=[status_list(length=8192)])
    add("status-index-out-of-range", "status", "error", "index beyond the list",
        credential=signed(credential(index=200000)), lists=[status_list()])
    add("status-list-expired", "status", "error", "validUntil of the list is in the past",
        credential=good, lists=[status_list(valid_until=NOW - 1)])
    add("status-list-unknown-key", "status", "error", "list signed with a key absent from the DID document",
        credential=good, lists=[status_list(key=key2)])
    return fixtures


def run_stack(stack, fixture: dict) -> dict:
    """Apply one verification stack to one fixture and return {"verdict", "detail"}."""
    documents = fixture["documents"]
    try:
        if fixture["operation"] == "credential":
            result = stack.verify_credential(fixture["credential"], documents, NOW)
            return {"verdict": "accept" if result["verified"] else "reject", "detail": result["category"]}
        if fixture["operation"] == "presentation":
            result = stack.verify_presentation(fixture["presentation"], documents, fixture["challenge"],
                                               fixture["domain"], NOW)
            return {"verdict": "accept" if result["verified"] else "reject", "detail": result["category"]}
        result = stack.check_status(fixture["credential"], fixture["lists"], documents, NOW)
        if not result["verified"]:
            return {"verdict": "error", "detail": "; ".join(result["messages"])[:160]}
        return {"verdict": "set" if any(s["status"] for s in result["statuses"]) else "clear", "detail": ""}
    except Exception as exc:
        return {"verdict": "exception", "detail": f"{type(exc).__name__}: {exc}"[:160]}


def compare(fixtures: list, python_stack, node_stack) -> dict:
    """Run both stacks over all fixtures and summarize agreement."""
    rows = []
    for fixture in fixtures:
        a, b = run_stack(python_stack, fixture), run_stack(node_stack, fixture)
        rows.append({"name": fixture["name"], "operation": fixture["operation"], "expect": fixture["expect"],
                     "note": fixture["note"], "python": a, "node": b, "agree": a["verdict"] == b["verdict"],
                     "python_as_expected": a["verdict"] == fixture["expect"],
                     "node_as_expected": b["verdict"] == fixture["expect"]})
    return {"fixtures": len(rows), "agree": sum(r["agree"] for r in rows),
            "python_as_expected": sum(r["python_as_expected"] for r in rows),
            "node_as_expected": sum(r["node_as_expected"] for r in rows), "rows": rows}


def save(fixtures: list, folder: str) -> None:
    import os
    os.makedirs(folder, exist_ok=True)
    for fixture in fixtures:
        with open(os.path.join(folder, fixture["name"] + ".json"), "w", encoding="utf-8", newline="\n") as handle:
            json.dump(fixture, handle, indent=1, sort_keys=True)
            handle.write("\n")
